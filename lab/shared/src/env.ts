import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Name of the shared secret the gateway uses when it calls a fake system. */
export const SERVICE_KEY_ENV = 'LAB_SERVICE_KEY';

/** Folder that holds the SQLite files. Git ignores it. */
export const DATA_DIR_ENV = 'LAB_DATA_DIR';

/**
 * Path of the rule file the gateway reads. A second process that writes the
 * same file resolves the path through the gateway module instead of guessing it.
 */
export const RULES_PATH_ENV = 'LAB_RULES_PATH';

/**
 * A key shorter than this cannot be the 32 random bytes generated by start.ts,
 * so the service refuses to run instead of silently accepting a weak value.
 */
export const SERVICE_KEY_MIN_LENGTH = 16;

/**
 * Read the service key without ever echoing it. Every service calls this on
 * startup so a missing key fails fast instead of leaving an open endpoint.
 */
export function readServiceKey(env: NodeJS.ProcessEnv = process.env): string {
  const key = env[SERVICE_KEY_ENV];
  if (key === undefined || key.trim().length < SERVICE_KEY_MIN_LENGTH) {
    throw new Error(`${SERVICE_KEY_ENV} must be set and at least ${SERVICE_KEY_MIN_LENGTH} characters long`);
  }
  return key;
}

/** Set to `1` to open the `/admin/*` routes the tests use. Anything else keeps them closed. */
export const TEST_HOOKS_ENV = 'LAB_TEST_HOOKS';

export function testHooksEnabled(env: NodeJS.ProcessEnv = process.env): boolean {
  return env[TEST_HOOKS_ENV] === '1';
}

/**
 * Folder for the SQLite files: `LAB_DATA_DIR` when set, otherwise `lab/.data`.
 * The default is found from this file (`lab/shared/dist`), so it does not
 * depend on the folder the process was started from.
 */
export function resolveDataDir(env: NodeJS.ProcessEnv = process.env): string {
  const configured = env[DATA_DIR_ENV];
  if (configured !== undefined && configured.trim() !== '') {
    return resolve(configured);
  }
  return resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '.data');
}

/** The address people open the confirmation links on. Defaults to the address the gateway listens on. */
export const PUBLIC_BASE_URL_ENV = 'LAB_PUBLIC_BASE_URL';

/**
 * The configured public address without a trailing slash, or undefined when it
 * is not set. A value that is not an http or https address stops the gateway
 * at startup, so no link in a tool answer points nowhere.
 */
export function readPublicBaseUrl(env: NodeJS.ProcessEnv = process.env): string | undefined {
  const configured = env[PUBLIC_BASE_URL_ENV]?.trim();
  if (configured === undefined || configured === '') return undefined;
  let url: URL;
  try {
    url = new URL(configured);
  } catch {
    throw new Error(`${PUBLIC_BASE_URL_ENV} must be an http or https address`);
  }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    throw new Error(`${PUBLIC_BASE_URL_ENV} must be an http or https address`);
  }
  return configured.replace(/\/+$/, '');
}
